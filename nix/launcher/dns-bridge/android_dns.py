"""DNS активной сети Android через небольшой APK, без ADB/root."""
import argparse
import base64
import ipaddress
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import time

COMPONENT = "io.emergy.androiddns/.NetworkReceiver"
ACTION = "io.emergy.androiddns.GET_NETWORK"
BLOCKED = "# Android DNS unavailable; external fallback disabled\nnameserver 127.0.0.1\noptions timeout:1 attempts:1\n"


def decode_response(output):
    match = re.search(r'Broadcast completed: result=0, data="ANDROID_DNS_V1:([A-Za-z0-9+/=]+)"', output)
    if match is None or len(match[1]) > 65536:
        raise ValueError("Нет ответа Android DNS Bridge. Установите и один раз откройте APK.")
    snapshot = json.loads(base64.b64decode(match[1], validate=True))
    if not isinstance(snapshot, dict) or type(snapshot.get("version")) is not int or snapshot["version"] != 1:
        raise ValueError("Неизвестная версия ответа DNS Bridge")
    timestamp = snapshot.get("captured_at_ms")
    if type(timestamp) is not int or abs(time.time() * 1000 - timestamp) > 120000:
        raise ValueError("Ответ DNS Bridge устарел")
    return snapshot


def query():
    user = os.environ.get("TERMUX__USER_ID", "0")
    if not user.isdecimal():
        raise ValueError("Некорректный Android user ID")
    result = subprocess.run(["am", "broadcast", "--user", user, "-n", COMPONENT, "-a", ACTION],
                            capture_output=True, text=True, timeout=20, check=True)
    return decode_response(result.stdout)


def render(snapshot):
    if snapshot.get("connected") is not True:
        return BLOCKED, "Нет активной сети: внешние DNS не используются"
    if snapshot.get("private_dns_active") is True:
        return BLOCKED, "Android Private DNS активен: обычный resolv.conf не обеспечивает шифрование; DNS заблокирован"
    servers = snapshot.get("dns_servers")
    if not isinstance(servers, list) or not servers:
        raise ValueError("Android не сообщил DNS-серверы")
    addresses = []
    for server in servers:
        if not isinstance(server, str) or not re.fullmatch(r"[0-9A-Fa-f:.]+(?:%[A-Za-z0-9_.-]{1,64})?", server):
            raise ValueError("Некорректный адрес DNS")
        address = ipaddress.ip_address(server)
        if address.is_unspecified or address.is_multicast:
            raise ValueError("Недопустимый адрес DNS")
        if server not in addresses:
            addresses.append(server)
    lines = ["# Generated by android-dns; uses Android active network"]
    domains = snapshot.get("domains")
    if domains is not None and not isinstance(domains, str):
        raise ValueError("Некорректный список поисковых доменов")
    search = []
    for name in re.split(r"[,\s]+", domains or ""):
        if not name:
            continue
        name = name.encode("idna").decode("ascii").rstrip(".")
        if len(name) > 253 or any(not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?", label) for label in name.split(".")):
            raise ValueError("Некорректный поисковый домен")
        if name not in search:
            search.append(name)
    if search:
        lines.append("search " + " ".join(search[:6]))
    lines.extend("nameserver " + server for server in addresses[:3])
    return "\n".join(lines) + "\n", None


def write_config(target, text):
    target = Path(target)
    if target.is_symlink():
        raise ValueError("Укажите обычный генерируемый файл, а не /etc/resolv.conf или другую ссылку")
    if target.exists() and target.read_text() == text:
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=".android-dns-", dir=target.parent)
    try:
        with os.fdopen(descriptor, "w") as output:
            output.write(text)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, target)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="показать сведения Android, ничего не менять")
    parser.add_argument("--output", type=Path, help="генерируемый файл; без этого параметра выводится предпросмотр")
    parser.add_argument("--watch", action="store_true", help="обновлять файл периодически, пока работает команда")
    parser.add_argument("--interval", type=float, default=30, help="интервал --watch в секундах, минимум 5")
    args = parser.parse_args()
    if args.json and args.output:
        parser.error("--json несовместим с --output")
    if args.watch and (not args.output or args.json):
        parser.error("--watch требует --output и несовместим с --json")
    if args.interval < 5:
        parser.error("--interval должен быть не меньше 5 секунд")
    last_warning = None
    while True:
        try:
            snapshot = query()
            if args.json:
                print(json.dumps(snapshot, ensure_ascii=False, indent=2))
                return 0
            text, warning = render(snapshot)
            if args.output:
                write_config(args.output, text)
            else:
                print(text, end="")
            if warning != last_warning and warning:
                print(warning, file=sys.stderr)
            last_warning = warning
            status = 1 if warning else 0
        except (OSError, ValueError, subprocess.SubprocessError) as error:
            warning = str(error)
            if warning != last_warning:
                print(warning, file=sys.stderr)
            last_warning = warning
            if args.watch:
                try:
                    write_config(args.output, BLOCKED)
                except (OSError, ValueError) as write_error:
                    print("Не удалось записать файл DNS: " + str(write_error), file=sys.stderr)
                    return 1
            status = 1
        if not args.watch:
            return status
        time.sleep(args.interval)


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        pass
